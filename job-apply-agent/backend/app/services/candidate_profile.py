    @classmethod
    def resolve_resume_pdf(
        cls,
        company: Optional[str] = None,
        job_title: Optional[str] = None,
        provided_path: Optional[str] = None
    ) -> Optional[str]:
        """Locates the tailored PDF generated by Agent 2, or falls back to master resume."""
        # 1. If exact path provided and exists
        if provided_path and os.path.exists(provided_path):
            return provided_path

        # 2. Check exports directory from Agent 2
        exports_dir = settings.RESUME_EXPORTS_DIR
        if os.path.exists(exports_dir):
            # Check for company or title match
            clean_company = "".join(c for c in (company or "") if c.isalnum() or c in (' ', '_', '-')).strip()
            clean_company = clean_company.replace(" ", "_").lower()
            
            candidates = glob.glob(os.path.join(exports_dir, "*.pdf"))
            # Sort newest first
            candidates.sort(key=os.path.getmtime, reverse=True)
            
            if clean_company:
                for c in candidates:
                    if clean_company in os.path.basename(c).lower():
                        return c
            
            # If no company match, return the newest generated PDF
            if candidates:
                return candidates[0]

        # 3. Fallback to master resume in Agent 1 or Agent 2
        fallbacks = [
            "/home/senkathir-selvan/job-find-agent/data/resume.pdf",
            "/home/senkathir-selvan/resume-prep-agent/data/master/resume_backup.pdf",
            "/home/senkathir-selvan/resume-prep-agent/data/master/master_resume.pdf"
        ]
        for fb in fallbacks:
            if os.path.exists(fb):
                return fb

        return None

